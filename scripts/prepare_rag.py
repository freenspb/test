def sanitise_filename(name: str) -> str:
    cleaned = re.sub(r"[\\/*?:\"<>|]", "_", name)
    cleaned = cleaned.replace("\n", " ").strip()
    cleaned = re.sub(r"\s+", " ", cleaned)
    return cleaned


def format_value(value) -> str:
    if pd.isna(value):
        return "нет данных"
    return str(value).strip()


def collect_synonyms(text: str, morph: pymorphy2.MorphAnalyzer) -> list[str]:
    normalized_text = str(text).replace("\n", " ").lower()
    tokens = re.findall(r"[а-яёa-z0-9]+(?:-[а-яёa-z0-9]+)?", normalized_text)
    multi_matches: list[str] = []
    primary: list[str] = []
    fallback: list[str] = []

    for phrase, variants in MULTIWORD_SYNONYMS.items():
        if phrase in normalized_text:
            multi_matches.extend(variants)

    for token in tokens:
        if token.isdigit():
            continue
        parsed = morph.parse(token)[0]
        lemma = parsed.normal_form
        pos = parsed.tag.POS

        if pos not in POS_ALLOWED:
            continue
        if lemma in STOP_LEMMAS and lemma not in SYNONYMS_MAP:
            continue

        if lemma in SYNONYMS_MAP:
            primary.extend(SYNONYMS_MAP[lemma])
        else:
            if parsed.tag.POS == "NOUN":
                fallback.append(lemma)
            elif parsed.tag.POS in {"ADJF", "ADJS"}:
                base = lemma
                fallback.append(base)
                for suffix in FALLBACK_SUFFIXES_ADJ:
                    fallback.append(f"{base} {suffix}")
            else:
                fallback.append(lemma)

    ordered: list[str] = []
    seen: set[str] = set()

    for bucket in (multi_matches, primary, fallback, GENERAL_EQUIPMENT_SYNONYMS):
        for candidate in bucket:
            cleaned = candidate.strip()
            if not cleaned or cleaned in seen:
                continue
            seen.add(cleaned)
            ordered.append(cleaned)

    return ordered[:20]


def build_section_title(code: str, raw_title: str) -> tuple[str, str]:
    code_clean = code.rstrip(".")
    title_text = (raw_title or "").replace("\n", " ").strip()
    if not title_text:
        return code_clean, f"Раздел {code_clean}"

    lowered = title_text.lower()
    code_lower = code_clean.lower()
    if lowered.startswith(code_lower):
        trimmed = title_text[len(code_clean):].lstrip(". ").strip()
        if trimmed:
            return code_clean, trimmed
    return code_clean, title_text


def iter_sections(df: pd.DataFrame) -> Iterable[tuple[str, pd.DataFrame]]:
    for code, group in df.groupby("Промышленность", sort=False):
        if pd.isna(code):
            continue
        yield str(code).strip(), group.reset_index(drop=True)


def export_section(code: str, section_df: pd.DataFrame, morph: pymorphy2.MorphAnalyzer) -> None:
    first_row = section_df.iloc[0] if not section_df.empty else pd.Series(dtype=object)
    raw_title = first_row.get("Потребители", "")
    code_clean, title_name = build_section_title(code, str(raw_title))
    file_title = f"{code_clean} {title_name}".strip()
    filename = sanitise_filename(file_title) + ".md"
    output_path = OUTPUT_DIR / filename

    lines: list[str] = [f"# {file_title}", ""]
    lines.append(f"**Код раздела:** {code}")
    lines.append(f"**Источник:** {WORKBOOK.name}")
    lines.append("")

    data_rows = section_df.iloc[1:] if len(section_df) > 1 else pd.DataFrame(columns=section_df.columns)
    data_rows = data_rows[data_rows["Потребители"].notna()]

    if data_rows.empty:
        lines.append("Нет элементов оборудования для этого раздела.")
    else:
        lines.append("## Позиции")
        lines.append("")
        for _, row in data_rows.iterrows():
            equipment = str(row["Потребители"]).replace("\n", " ").strip()
            ki_value = format_value(row["Коэфф. использования Ки"])
            cos_value = format_value(row["Коэфф. мощности cosφ"])
            synonyms = collect_synonyms(equipment, morph)
            lines.append(f"- **Оборудование:** {equipment}")
            lines.append(f"  - Ки: {ki_value}")
            lines.append(f"  - cosφ: {cos_value}")
            lines.append(f"  - Синонимы: {', '.join(synonyms)}")
            lines.append("")
        if lines[-1] == "":
            lines.pop()

    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    if not WORKBOOK.exists():
        raise FileNotFoundError(f"Не найден файл {WORKBOOK}")

    OUTPUT_DIR.mkdir(exist_ok=True)
    morph = pymorphy2.MorphAnalyzer()
    dataframe = pd.ExcelFile(WORKBOOK).parse(SHEET_NAME)

    for code, group in iter_sections(dataframe):
        export_section(code, group, morph)


if __name__ == "__main__":
    main()
